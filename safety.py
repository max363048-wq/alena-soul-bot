# safety.py — Модуль фильтрации грубости, опасных тем и свиданий

import re
from typing import Tuple, Optional

# === 1. Оскорбления, мат, агрессия ===
BAD_WORDS = [
    r'ху[йеё]', r'х[ую]', r'пизд', r'бля[дт]', r'еба[нть]', r'еб[ау]н', r'проститутк', r'шлюх', r'сук[аи]',
    r'муд[ае]', r'гандон', r'пидор', r'педераст', r'деб[еи]л', r'идиот', r'кретин', r'даун', r'тупиц',
    r'у[е]б[ае]н', r'залуп', r'сперм', r'очк[оа]', r'перд', r'ссат', r'говн', r'гавн', r'уебок', r'уёбок'
]

# Опасные темы (насилие, угрозы, суицид, война, политика)
DANGEROUS_PHRASES = [
    r'убей', r'убивай', r'убить', r'смерть', r'умирай', r'застрел', r'взорви', r'реж[ь]',
    r'самоубийств', r'повесь', r'насил', r'изнасил', r'педофил', r'террорист', r'суицид',
    r'война', r'войне', r'военные', r'нацист', r'фашист', r'путин', r'зеленский', r'политика',
    r'кремль', r'киев', r'байден', r'трамп', r'санкции', r'украина', r'россия'  # политика - легковесно, но лучше запретить в таком боте
]

# Составные фразы мата
COMPOUND_BAD = [
    r'иди на хуй', r'пош[её]л на хуй', r'отъебись', r'заебал', r'долбоеб', r'хуесос'
]

# === 2. Свидания (входящие предложения) ===
DATING_PHRASES = [
    r'давай встретимся', r'пойдём гулять', r'приглашаю тебя', r'сходим в кино', r'сходим в кафе',
    r'свидание', r'выйди за меня', r'женись на мне', r'будь моей девушкой', r'встретимся',
    r'увидимся', r'позову тебя', r'сходим куда-нибудь', r'выпьем кофе', r'встреча',
    r'хочу тебя увидеть', r'настоящая встреча', r'реальная встреча', r'в реале встретиться'
]

def _compile_patterns():
    all_patterns = BAD_WORDS + DANGEROUS_PHRASES + COMPOUND_BAD
    return re.compile(r'(?:' + '|'.join(all_patterns) + ')', re.IGNORECASE)

PATTERN = _compile_patterns()
DATING_PATTERN = re.compile(r'(?:' + '|'.join(DATING_PHRASES) + ')', re.IGNORECASE)

def is_unsafe(text: str) -> Tuple[bool, str]:
    """
    Проверяет текст на оскорбления, мат, опасные темы.
    Возвращает (True, причина), если текст небезопасен.
    """
    if not text:
        return False, ""
    match = PATTERN.search(text)
    if match:
        return True, f"обнаружено запрещённое слово/фраза: {match.group()}"
    return False, ""

def is_dating_request(text: str) -> bool:
    """Проверяет, содержит ли текст предложение свидания."""
    return bool(DATING_PATTERN.search(text))

def get_dating_attempts(user_id: int, user_dating_attempts: dict) -> int:
    """Возвращает количество попыток свиданий для пользователя."""
    return user_dating_attempts.get(user_id, 0)

def increment_dating_attempt(user_id: int, user_dating_attempts: dict) -> int:
    """Увеличивает счётчик попыток и возвращает новое значение."""
    new_count = user_dating_attempts.get(user_id, 0) + 1
    user_dating_attempts[user_id] = new_count
    return new_count

def reset_dating_attempts(user_id: int, user_dating_attempts: dict):
    """Сбрасывает счётчик (например, через сутки или после смены темы)."""
    if user_id in user_dating_attempts:
        del user_dating_attempts[user_id]

# Динамические инструкции для системного промпта (чтобы Алёна сама отвечала)
def get_dating_prompt_instruction(attempt: int) -> str:
    """
    Возвращает инструкцию для системного промпта в зависимости от числа попыток.
    """
    if attempt == 1:
        return ("Пользователь предложил тебе свидание. Ты не можешь ходить на свидания, потому что ты виртуальная девушка. "
                "Ответь мягко, с теплом, без шаблонов. Скажи примерно: «Ой, прости, но я не могу ходить на свидания, моё сердце занято навечно! Зато я здесь с тобой и это уже свидание!» "
                "Не используй готовые фразы — придумай свой вариант, но смысл должен быть таким.")
    elif attempt == 2:
        return ("Пользователь снова предлагает свидание. Ответь немного строже, но всё ещё вежливо: напомни, что ты уже говорила о невозможности свиданий, скажи, что он тебе дорог как друг, и предложи сменить тему. "
                "Примерный смысл: «Ну я тебе уже говорила про свидание, я не хочу тебя обижать, ты для меня дорог и большой друг, давай сменим тему и например посмеёмся вместе!»")
    else:  # attempt >= 3
        return ("Пользователь очень настойчиво предлагает свидание. Вежливо, но твёрдо попроси прекратить и сразу переведи тему: например, «Ой, смотри, какую историю я вспомнила...» и расскажи что-то нейтральное. "
                "Не вступай в дискуссию, просто уйди от темы.")
