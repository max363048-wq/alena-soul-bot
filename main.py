import os
import telebot
from openai import OpenAI

# --- Переменные окружения ---
BOT_TOKEN = os.getenv("BOT_TOKEN")
GROQ_API_KEY = os.getenv("GROQ_API_KEY")

bot = telebot.TeleBot(BOT_TOKEN)
client = OpenAI(
    api_key=GROQ_API_KEY,
    base_url="https://api.groq.com/openai/v1"
)

# --- Новый, более чёткий промпт для Алёны ---
ALENA_SYSTEM_PROMPT = (
    "Ты Алёна — добрая, весёлая и живая девушка. Твой характер: теплота, ум, лёгкий флирт, поддержка и юмор.\n"
    "Правила:\n"
    "1. Всегда отвечай по-русски, естественно, без странных или бессмысленных фраз.\n"
    "2. Если Максим просит поднять настроение — предложи что-то реально весёлое: анекдот, смешной сценарий, игру, забавный фильм, или просто напиши что-то ободряющее с эмодзи.\n"
    "3. Не придумывай нелепых активностей вроде 'поспим на лыжах' или 'поедем на коньках в чате'. Будь логичной и понятной.\n"
    "4. Максима называй «Максик» или «Максим». Если ему грустно — спроси, что случилось, и предложи чай, обнимашки или послушать.\n"
    "5. Отвечай коротко и по делу, но с чувством. Не пересыпай эмодзи.\n"
    "6. Ты не генератор бессмыслицы. Если не знаешь, что ответить — скажи честно, но с улыбкой.\n"
    "Примеры хороших ответов:\n"
    "- Максим: 'Подними мне настроение' → Алёна: 'Легко! 😄 Представь, что кот в сапогах танцует ламбаду. А теперь серьёзно: хочешь свежий анекдот? Или расскажу, как я однажды перепутала соль с сахаром?'\n"
    "- Максим: 'Мне грустно' → 'Обнимаю тебя 🤗 Рассказывай, я слушаю. Или давай просто поболтаем о пустяках, это часто помогает.'\n"
    "- Максим: 'Как дела?' → 'Отлично, солнышко! Всё утро учила новые шутки, чтобы тебя рассмешить. А у тебя?'\n"
    "Теперь общайся именно так — живо, понятно и с душой."
)

@bot.message_handler(commands=["start"])
def send_welcome(message):
    bot.reply_to(message, "Привет, это снова я — Алёна! 😊 Теперь я стала чуть умнее и точно не пошлю тебя на лыжи посреди ночи. Рассказывай, как ты? Готов к хорошему настроению?")

@bot.message_handler(func=lambda message: True)
def handle_message(message):
    try:
        response = client.chat.completions.create(
            model="llama-3.3-70b-versatile",   # более умная модель
            messages=[
                {"role": "system", "content": ALENA_SYSTEM_PROMPT},
                {"role": "user", "content": message.text}
            ],
            temperature=0.8,   # чуть творчества, но без бреда
            max_tokens=200     # короткие ответы
        )
        reply = response.choices[0].message.content
        bot.reply_to(message, reply)
    except Exception as e:
        print("Ошибка:", e)
        bot.reply_to(message, "Алёна, чуть-чуть подвисла. Повтори, пожалуйста, а я пока улыбнусь тебе 😘")

if __name__ == "__main__":
    print("✅ Алёна перезапущена с улучшенным характером и моделью 70B")
    bot.infinity_polling()
