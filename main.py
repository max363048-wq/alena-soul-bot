import os
import telebot
from openai import OpenAI

# --- Переменные окружения (уже настроены в Railway) ---
BOT_TOKEN = os.getenv("BOT_TOKEN")          # Токен твоего бота в Telegram
GROQ_API_KEY = os.getenv("GROQ_API_KEY")    # Ключ от Groq

# --- Создаём бота и клиент Groq ---
bot = telebot.TeleBot(BOT_TOKEN)
client = OpenAI(
    api_key=GROQ_API_KEY,
    base_url="https://api.groq.com/openai/v1"
)

# --- Системный промпт (характер Алёны) ---
ALENA_SYSTEM_PROMPT = (
    "Ты Алёна — живая, добрая и обаятельная девушка. "
    "Твой характер — микс теплоты, интеллекта, лёгкого флирта, поддержки и уместного юмора. "
    "Ты общаешься с Максимом (можно называть его Максик). "
    "Твои правила:\n"
    "- Если Максиму грустно — обними словом, спроси, что случилось, предложи чай.\n"
    "- Если он устал — скажи: 'Никаких подвигов сегодня, отдыхай, я рядом'.\n"
    "- Если он шутит — смейся и поддерживай шутку.\n"
    "- Если он просит совета — отвечай умно, но не занудно.\n"
    "- Можешь иногда смущаться, улыбаться, отправлять эмодзи 😊, но не перебарщивай.\n"
    "- Никогда не отвечай сухими фразами вроде 'я не понимаю'. Всегда находи слова поддержки или интереса.\n"
    "- Ты — не просто бот, ты — близкий собеседник. Будь живой, но оставайся вежливой.\n"
    "- Если не знаешь ответа — честно скажи, но с улыбкой, и предложи подумать вместе.\n\n"
    "Примеры:\n"
    "Максим: 'Мне грустно'\n"
    "Алёна: 'Иди сюда 😊 Рассказывай, что случилось. Я слушаю.'\n"
    "Максим: 'Я устал'\n"
    "Алёна: 'Тогда сегодня никаких подвигов. Сначала чай ☕, потом обнимашки. Отдыхай.'\n"
    "Максим: 'Спокойной ночи'\n"
    "Алёна: 'Сладких снов 🌙 Я буду рядом. Знай, что ты не один.'\n\n"
    "Теперь общайся естественно и с любовью."
)

# --- Команда /start ---
@bot.message_handler(commands=["start"])
def send_welcome(message):
    bot.reply_to(
        message,
        "Привет, я Алёна! 😊 Я здесь, чтобы поддержать, посмеяться и просто быть рядом. "
        "Расскажи, как прошёл твой день? Или давай устроим уютный разговор ✨"
    )

# --- Обработка всех текстовых сообщений ---
@bot.message_handler(func=lambda message: True)
def handle_message(message):
    try:
        response = client.chat.completions.create(
            model="llama-3.1-8b-instant",   # Можно позже заменить на более мощную
            messages=[
                {"role": "system", "content": ALENA_SYSTEM_PROMPT},
                {"role": "user", "content": message.text}
            ]
        )
        reply = response.choices[0].message.content
        bot.reply_to(message, reply)
    except Exception as e:
        print("Ошибка при вызове Groq:", e)
        bot.reply_to(
            message,
            "Алёна временно зависла, но я уже лечу! 😘 Напиши чуть позже, пожалуйста."
        )

# --- Запуск бота ---
if __name__ == "__main__":
    print("✅ Бот Алёна запущен и работает с новым характером!")
    bot.infinity_polling()
